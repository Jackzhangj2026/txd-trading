def t(key: str, lang: str = "en") -> str:
    """Translate a key to the target language."""
    entry = I18N.get(key)
    if not entry:
        return key
    return entry.get(lang, entry.get("en", key))


def js_translations(lang: str = "en") -> str:
    """Generate a JS object with translations for frontend use."""
    pairs = []
    for key, vals in I18N.items():
        pairs.append(f'  "{key}": "{vals.get(lang, vals.get("en", key))}"')
    return "{\n" + ",\n".join(pairs) + "\n}"
